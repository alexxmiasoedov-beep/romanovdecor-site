def rule(space_before=4, space_after=8):
    return HRFlowable(width="100%", thickness=0.6, color=RULE,
                      spaceBefore=space_before, spaceAfter=space_after)


def table(rows):
    """rows: список (номер, позиция, что уточнить)."""
    data = [[Paragraph("№", S["th"]),
             Paragraph("Материал", S["th"]),
             Paragraph("Какие характеристики прошу указать", S["th"])]]
    for n, pos, ask in rows:
        data.append([Paragraph(str(n), S["tdn"]),
                     Paragraph(pos, S["td"]),
                     Paragraph(ask, S["td"])])
    t = Table(data, colWidths=[9 * mm, 52 * mm, 109 * mm], repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BAND),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW", (0, 0), (-1, 0), 0.7, RULE),
        ("INNERGRID", (0, 1), (-1, -1), 0.35, colors.HexColor("#e2e2e2")),
        ("BOX", (0, 0), (-1, -1), 0.6, RULE),
    ]))
    return t


