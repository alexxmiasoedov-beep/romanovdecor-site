def build_sheet(ws, title, subtitle, rows):
    for i, (name, width) in enumerate(COLS, 1):
        ws.column_dimensions[get_column_letter(i)].width = width

    last = get_column_letter(len(COLS))

    ws.merge_cells(f"A1:{last}1")
    ws["A1"] = title
    ws["A1"].font = TITLE_F
    ws.row_dimensions[1].height = 22

    ws.merge_cells(f"A2:{last}2")
    ws["A2"] = subtitle
    ws["A2"].font = SUB_F
    ws["A2"].alignment = Alignment(wrap_text=True, vertical="top")
    ws.row_dimensions[2].height = 30

    ws.merge_cells(f"A4:{last}4")
    ws["A4"] = ("Как заполнять: колонки A–D заполнены нами, менять их не нужно. "
                "Прошу заполнить жёлтые колонки E–O. Если позиции нет — достаточно "
                "поставить «Нет» в колонке «Наличие», остальное можно пропустить. "
                "Цены — за килограмм, в валюте на ваше усмотрение, с указанием НДС "
                "в примечании. Строка 7 — пример заполнения, её можно удалить.")
    ws["A4"].font = SUB_F
    ws["A4"].alignment = Alignment(wrap_text=True, vertical="top")
    ws.row_dimensions[4].height = 40

    for i, (name, _) in enumerate(COLS, 1):
        c = ws.cell(row=HDR_ROW, column=i, value=name)
        c.font = HDR_F
        c.fill = HDR_OUR if i <= N_OUR else HDR_ASK
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.border = BORDER
    ws.row_dimensions[HDR_ROW].height = 30

    for i, v in enumerate(EXAMPLE, 1):
        c = ws.cell(row=EX_ROW, column=i, value=v)
        c.font = EX_F
        c.fill = EX_FILL
        c.alignment = Alignment(wrap_text=True, vertical="top")
        c.border = BORDER
    ws.row_dimensions[EX_ROW].height = 26

    for n, (mat, need, ask) in enumerate(rows, 1):
        r = FIRST + n - 1
        vals = [n, mat, need, ask] + [None] * (len(COLS) - N_OUR)
        for i, v in enumerate(vals, 1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = CELL_F
            c.fill = GREY_FILL if i <= N_OUR else ASK_FILL
            c.alignment = Alignment(wrap_text=True, vertical="top",
                                    horizontal="center" if i == 1 else "left")
            c.border = BORDER
        ws.row_dimensions[r].height = 34

    end = FIRST + len(rows) - 1

    dv = DataValidation(type="list",
                        formula1='"Есть на складе,Под заказ,Нет"',
                        allow_blank=True, showDropDown=False)
    ws.add_data_validation(dv)
    dv.add(f"E{FIRST}:E{end}")

    s = end + 2
    ws.cell(row=s, column=2, value="Позиций в перечне").font = SUM_F
    ws.cell(row=s, column=3, value=len(rows)).font = SUM_F

    ws.cell(row=s + 2, column=2,
            value="ИП Мясоедов Алексей Владимирович · +375 33 628-04-86 · "
                  "miasoedov95@gmail.com").font = SUB_F

    ws.freeze_panes = f"E{FIRST}"
    ws.auto_filter.ref = f"A{HDR_ROW}:{last}{end}"
    ws.sheet_view.zoomScale = 90


wb = Workbook()
ws1 = wb.active
