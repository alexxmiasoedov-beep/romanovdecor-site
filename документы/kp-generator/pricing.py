#!/usr/bin/env python3
# Прайс на микроцемент. Продаём материал, работы не выполняем.
# Правило: РРЦ полов = РРЦ стен + DELTA. Тогда при любой дилерской
# скидке наша маржа на стенах и полах одинакова.
from costs import cost, WALL, FLOOR, RATE

MAT = {'стены': cost(WALL), 'полы': cost(FLOOR)}   # себестоимость, $/м²

DELTA = 16          # надбавка полов к стенам, $/м²
MIN_M2 = 20         # минимальная поставка
D_FROM, D_TO = 35, 120
RRC_HI, RRC_LO = 40, 34            # РРЦ стен: старт и дно

DEALERS = [('Дилер', 'стартовый, от 100 м² в квартал', 0.30),
           ('Дилер', 'от 500 м² в год', 0.35),
           ('Генеральный', 'регион, от 1500 м² в год', 0.40)]

WORK_REF = {'стены': 24, 'полы': 25}   # справка: что берут бригады за работу

KIT = 100           # базовый комплект, м² — ограничен ведром лака 10 кг


def rrc(a, k):
    """РРЦ за м² по объёму объекта."""
    a = max(a, MIN_M2)
    if a <= D_FROM:  base = float(RRC_HI)
    elif a >= D_TO:  base = float(RRC_LO)
    else:            base = RRC_HI - (RRC_HI - RRC_LO) * (a - D_FROM) / (D_TO - D_FROM)
    return base + (DELTA if k == 'полы' else 0)


def byn(v): return f'{v * RATE:,.0f}'.replace(',', ' ')


def retail():
    print('ПРАЙС 1 — РРЦ, КОНЕЧНЫЙ КЛИЕНТ, $/м²')
    print(f'  {"объём":>7}{"стены":>9}{"полы":>9}   при работе бригады под ключ выйдет')
    for a in (20, 35, 50, 80, 100, 120, 200):
        w, f = rrc(a, 'стены'), rrc(a, 'полы')
        print(f'  {a:>5} м²{w:>9.2f}{f:>9.2f}      стены {w + WORK_REF["стены"]:>6.2f}   '
              f'полы {f + WORK_REF["полы"]:>6.2f}')
    print(f'  Полы = стены + ${DELTA} на любой ступени.')


def dealers():
    print('\nПРАЙС 2 — ДИЛЕРЫ, $/м² (скидка от базовой РРЦ, объёмная не суммируется)')
    print(f'  {"уровень":<13}{"условие":<32}{"скид":>6}{"стены":>8}{"наша":>7}'
          f'{"полы":>8}{"наша":>7}{"дилер зарабатывает":>21}')
    for name, cond, disc in DEALERS:
        w = RRC_HI * (1 - disc)
        f = (RRC_HI + DELTA) * (1 - disc)
        print(f'  {name:<13}{cond:<32}{disc:>5.0%}{w:>8.2f}{w - MAT["стены"]:>7.2f}'
              f'{f:>8.2f}{f - MAT["полы"]:>7.2f}'
              f'{"стены " + format(RRC_HI - w, ".2f"):>13}'
              f'{" полы " + format(RRC_HI + DELTA - f, ".2f"):>8}')


def kits():
    print(f'\nКОМПЛЕКТ {KIT} м² — минимальная партия (упирается в ведро лака 10 кг)')
    print(f'  {"":<14}{"себестоимость":>15}{"дилер −30%":>13}{"дилер −40%":>13}{"РРЦ":>10}')
    for k in ('стены', 'полы'):
        base = RRC_HI + (DELTA if k == 'полы' else 0)
        print(f'  {k:<14}{MAT[k] * KIT:>15,.0f}{base * .70 * KIT:>13,.0f}'
              f'{base * .60 * KIT:>13,.0f}{base * KIT:>10,.0f}')
    print(f'  В рублях по курсу {RATE}: РРЦ комплекта стен '
          f'{byn(RRC_HI * KIT)}, полов {byn((RRC_HI + DELTA) * KIT)}')


def check():
    print('\nПРОВЕРКА: наша маржа с метра при разной глубине скидки')
    print(f'  {"скидка":>7}{"стены":>9}{"полы":>9}{"разница":>10}')
    for disc in (0.0, 0.30, 0.35, 0.40, 0.45, 0.50):
        w = RRC_HI * (1 - disc) - MAT['стены']
        f = (RRC_HI + DELTA) * (1 - disc) - MAT['полы']
        flag = '   ← дно' if min(w, f) < 8 else ''
        print(f'  {disc:>6.0%}{w:>9.2f}{f:>9.2f}{f - w:>10.2f}{flag}')


if __name__ == '__main__':
    print(f'Себестоимость: стены ${MAT["стены"]:.2f}   полы ${MAT["полы"]:.2f}\n')
    retail()
    dealers()
    kits()
    check()
