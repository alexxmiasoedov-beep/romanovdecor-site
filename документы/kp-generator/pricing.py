#!/usr/bin/env python3
# Прайс на микроцемент. Продаём материал, работы не выполняем.
# РРЦ не меняется — она уже в рынке. Регулируем только глубину
# дилерской скидки. После перехода на смолу за 20 BYN/кг полы
# догнали стены, поэтому глубина у них теперь одинаковая.
from costs import cost, WALL, FLOOR, RATE

MAT = {'стены': cost(WALL), 'полы': cost(FLOOR)}   # себестоимость, $/м²

MIN_M2 = 20         # минимальная поставка
D_FROM, D_TO = 35, 120
RRC = {'стены': (40, 34), 'полы': (50, 45)}   # база и дно по объёму

# 30% хватает только тому, кто берёт для себя: у него нет ни отката,
# ни торга. Перепродавцу нужно от 40%.
DEALERS = [('Мастер', 'для себя, без перепродажи, от 50 м²', 0.30, 0.30),
           ('Дилер на УСН', 'базовый, от 300 м² в квартал', 0.40, 0.40),
           ('Дилер на ОСН', 'базовый, от 300 м² в квартал', 0.45, 0.45),
           ('Дилер на ОСН', 'крупный, от 1000 м² в год', 0.48, 0.48),
           ('Генеральный', 'регион, от 2500 м² в год', 0.50, 0.50)]

WORK_REF = {'стены': 24, 'полы': 25}   # справка: что берут бригады за работу

KIT = 100           # базовый комплект, м² — ограничен ведром лака 10 кг


def rrc(a, k):
    """РРЦ за м² по объёму объекта."""
    hi, lo = RRC[k]
    a = max(a, MIN_M2)
    if a <= D_FROM: return float(hi)
    if a >= D_TO:   return float(lo)
    return hi - (hi - lo) * (a - D_FROM) / (D_TO - D_FROM)


def byn(v): return f'{v * RATE:,.0f}'.replace(',', ' ')


def retail():
    print('ПРАЙС 1 — РРЦ, КОНЕЧНЫЙ КЛИЕНТ, $/м²')
    print(f'  {"объём":>7}{"стены":>9}{"полы":>9}   при работе бригады под ключ выйдет')
    for a in (20, 35, 50, 80, 100, 120, 200):
        w, f = rrc(a, 'стены'), rrc(a, 'полы')
        print(f'  {a:>5} м²{w:>9.2f}{f:>9.2f}      стены {w + WORK_REF["стены"]:>6.2f}   '
              f'полы {f + WORK_REF["полы"]:>6.2f}')
    print('  РРЦ не трогаем — она уже в рынке.')


def dealers():
    print('\nПРАЙС 2 — ДИЛЕРЫ, $/м² (скидка от базовой РРЦ, объёмная не суммируется)')
    print(f'  {"уровень":<13}{"условие":<30}{"скид":>6}{"стены":>8}{"наша":>7}'
          f'{"скид":>6}{"полы":>8}{"наша":>7}{"дилер зарабатывает":>21}')
    for name, cond, dw, df in DEALERS:
        w = RRC['стены'][0] * (1 - dw)
        f = RRC['полы'][0] * (1 - df)
        print(f'  {name:<13}{cond:<30}{dw:>5.0%}{w:>8.2f}{w - MAT["стены"]:>7.2f}'
              f'{df:>6.0%}{f:>8.2f}{f - MAT["полы"]:>7.2f}'
              f'{"стены " + format(RRC["стены"][0] - w, ".2f"):>13}'
              f'{" полы " + format(RRC["полы"][0] - f, ".2f"):>8}')


def kits():
    print(f'\nКОМПЛЕКТ {KIT} м² — минимальная партия (упирается в ведро лака 10 кг)')
    print(f'  {"":<14}{"себестоимость":>15}{"дилер −40%":>13}{"дно":>13}{"РРЦ":>10}')
    for k in ('стены', 'полы'):
        base = RRC[k][0]
        deep = .50
        print(f'  {k:<14}{MAT[k] * KIT:>15,.0f}{base * .60 * KIT:>13,.0f}'
              f'{base * deep * KIT:>13,.0f}{base * KIT:>10,.0f}')
    print(f'  В рублях по курсу {RATE}: РРЦ комплекта стен '
          f'{byn(RRC["стены"][0] * KIT)}, полов {byn(RRC["полы"][0] * KIT)}')


def check():
    print('\nПРОВЕРКА: наша маржа с метра при разной глубине скидки')
    print(f'  {"скидка":>7}{"стены":>9}{"полы":>9}{"разница":>10}')
    for disc in (0.0, 0.30, 0.35, 0.40, 0.45, 0.50, 0.55):
        w = RRC['стены'][0] * (1 - disc) - MAT['стены']
        f = RRC['полы'][0] * (1 - disc) - MAT['полы']
        mark = ('  стены ещё держат, полы уже нет' if w >= 8 > f else
                '  дно по обоим' if w < 8 else '')
        print(f'  {disc:>6.0%}{w:>9.2f}{f:>9.2f}{f - w:>10.2f}{mark}')




# ── экономика дилера ──────────────────────────────────────────────────────
KICKBACK = 0.10   # откат прорабу или дизайнеру, % от суммы сделки
TAX = 0.06        # налог, УСН с валовой выручки
HAGGLE = 0.07     # типовая уступка клиенту при торге, % от РРЦ
VAT = 0.20        # НДС
PROFIT_TAX = 0.20 # налог на прибыль на общей системе

# Мы сами на ОСН: входной НДС по закупке зачитывается, НДС с продажи
# начисляется. В деньгах это значит, что и цена, и себестоимость
# считаются без НДС, а с разницы платится налог на прибыль.
OUR_OSN = True


def dealer_pl(disc, k='стены', t=HAGGLE):
    """Прибыль дилера с метра при скидке disc."""
    R = RRC[k][0]
    P = R * (1 - t)                 # цена продажи после торга
    return P * (1 - KICKBACK - TAX) - R * (1 - disc)


def breakeven(t=HAGGLE):
    """Скидка, при которой дилер выходит в ноль."""
    return 1 - (1 - t) * (1 - KICKBACK - TAX)


def max_haggle(disc):
    """Насколько дилер может уступить клиенту, оставаясь в нуле."""
    return 1 - (1 - disc) / (1 - KICKBACK - TAX)


def dealer_economics():
    print('\nЭКОНОМИКА ДИЛЕРА, $/м² (откат 10%, налог 6% УСН, торг 7%)')
    print(f'  точка безубыточности дилера: скидка {breakeven():.1%}')
    print(f'  {"скидка":>7}{"стены":>9}{"полы":>9}{"% от РРЦ":>11}'
          f'{"запас на торг":>15}{"наша маржа стены":>18}{"полы":>8}')
    for disc in (0.30, 0.35, 0.40, 0.45, 0.50):
        w, f = dealer_pl(disc, 'стены'), dealer_pl(disc, 'полы')
        print(f'  {disc:>6.0%}{w:>9.2f}{f:>9.2f}{w / RRC["стены"][0]:>11.1%}'
              f'{max_haggle(disc):>15.1%}'
              f'{RRC["стены"][0] * (1 - disc) - MAT["стены"]:>18.2f}'
              f'{RRC["полы"][0] * (1 - disc) - MAT["полы"]:>8.2f}')


def what_eats():
    print('\nЧТО СЪЕДАЕТ СКИДКУ ДИЛЕРА, пункты от РРЦ')
    print(f'  торг с клиентом      {HAGGLE:>6.1%}')
    print(f'  откат прорабу        {KICKBACK * (1 - HAGGLE):>6.1%}   (10% от цены продажи)')
    print(f'  налог УСН            {TAX * (1 - HAGGLE):>6.1%}   (6% от цены продажи)')
    print(f'  ─────────────────────────────')
    print(f'  до нуля              {breakeven():>6.1%}   ← меньше этой скидки дилер в убытке')



def dealer_pl_osn(disc, k='стены', t=HAGGLE, vat_credit=True):
    """Прибыль дилера на общей системе: НДС 20% + налог на прибыль 20%.
    vat_credit=False — мы не плательщики НДС и не даём ЭСЧФ, входного
    вычета у дилера нет и НДС ложится на всю выручку."""
    R = RRC[k][0]
    P = R * (1 - t)
    Z = R * (1 - disc)
    base = (P - Z) / (1 + VAT) if vat_credit else P - P * VAT / (1 + VAT) - Z
    return base * (1 - PROFIT_TAX) - KICKBACK * P


def osn_table():
    print('\nДИЛЕР НА ОБЩЕЙ СИСТЕМЕ (НДС 20% + прибыль 20%), $/м²')
    print(f'  {"скид":>5}{"УСН стены":>11}{"полы":>7}{"ОСН стены":>11}{"полы":>7}'
          f'{"% оборота":>11}{"без ЭСЧФ":>10}{"наша стены":>12}{"полы":>7}')
    for disc in (0.30, 0.35, 0.40, 0.45, 0.48, 0.50):
        P = RRC['стены'][0] * (1 - HAGGLE)
        o = dealer_pl_osn(disc, 'стены')
        print(f'  {disc:>4.0%}{dealer_pl(disc, "стены"):>11.2f}{dealer_pl(disc, "полы"):>7.2f}'
              f'{o:>11.2f}{dealer_pl_osn(disc, "полы"):>7.2f}{o / P:>11.1%}'
              f'{dealer_pl_osn(disc, "стены", vat_credit=False):>10.2f}'
              f'{RRC["стены"][0] * (1 - disc) - MAT["стены"]:>12.2f}'
              f'{RRC["полы"][0] * (1 - disc) - MAT["полы"]:>7.2f}')
    print('  Колонка «без ЭСЧФ» — если мы не плательщики НДС: у дилера нет')
    print('  входного вычета, и никакая скидка его не спасает.')




def net(price_gross, k):
    """Наша чистая прибыль с метра после НДС и налога на прибыль."""
    gross = price_gross - MAT[k]
    if not OUR_OSN:
        return gross
    return gross / (1 + VAT) * (1 - PROFIT_TAX)


def our_pl():
    print('\nНАША ПРИБЫЛЬ С МЕТРА (мы на ОСН)')
    print(f'  себестоимость без НДС: стены ${MAT["стены"] / (1 + VAT):.2f}   '
          f'полы ${MAT["полы"] / (1 + VAT):.2f}')
    print(f'  {"канал":<22}{"стены цена":>12}{"валовая":>10}{"чистая":>9}'
          f'{"полы цена":>12}{"валовая":>10}{"чистая":>9}')
    rows = [('Прямая продажа, РРЦ', 0.0)] + [(f'{n}, −{d:.0%}', d) for n, c, d, _ in DEALERS]
    for label, disc in rows:
        w, f = RRC['стены'][0] * (1 - disc), RRC['полы'][0] * (1 - disc)
        print(f'  {label:<22}{w:>12.2f}{w - MAT["стены"]:>10.2f}{net(w, "стены"):>9.2f}'
              f'{f:>12.2f}{f - MAT["полы"]:>10.2f}{net(f, "полы"):>9.2f}')
    print('  Чистая — после НДС и налога на прибыль, но до аренды, логистики,')
    print('  зарплат и рекламы. Это не прибыль компании, это вклад метра.')




# ── дилерская шкала по месячному объёму ───────────────────────────────────
# Скидка следующего месяца назначается по объёму текущего.
MONTHLY = [(0,    0.30, 'без договора, до 300 м²'),
           (300,  0.34, 'дилер, от 300 м² в месяц'),
           (600,  0.37, 'от 600 м² в месяц'),
           (1000, 0.40, 'от 1000 м² в месяц')]


def tier(v):
    d = MONTHLY[0][1]
    for lo, disc, _ in MONTHLY:
        if v >= lo: d = disc
    return d


def monthly_table():
    print('\nДИЛЕРСКАЯ ШКАЛА ПО МЕСЯЧНОМУ ОБЪЁМУ')
    print(f'  {"порог":<22}{"скид":>6}{"стены":>8}{"полы":>8}'
          f'{"дилер стены":>13}{"полы":>7}{"наша стены":>12}{"полы":>7}')
    for lo, disc, label in MONTHLY:
        w, f = RRC['стены'][0] * (1 - disc), RRC['полы'][0] * (1 - disc)
        print(f'  {label:<22}{disc:>5.0%}{w:>8.2f}{f:>8.2f}'
              f'{dealer_pl_osn(disc, "стены"):>13.2f}{dealer_pl_osn(disc, "полы"):>7.2f}'
              f'{net(w, "стены"):>12.2f}{net(f, "полы"):>7.2f}')
    print('\n  Наши деньги в месяц (чистыми после налогов, объём по стенам):')
    print(f'  {"м²/мес":>8}{"скидка":>9}{"наш $/мес":>12}{"дилеру $/мес":>15}')
    for v in (100, 250, 400, 500, 800, 1000, 1500):
        d = tier(v)
        print(f'  {v:>8}{d:>9.0%}{net(RRC["стены"][0] * (1 - d), "стены") * v:>12,.0f}'
              f'{dealer_pl_osn(d, "стены") * v:>15,.0f}')
    print('\n  Проверка порогов: теряем ли мы на переходе')
    for i in range(1, len(MONTHLY)):
        lo = MONTHLY[i][0]
        before = net(RRC['стены'][0] * (1 - MONTHLY[i - 1][1]), 'стены') * lo
        after = net(RRC['стены'][0] * (1 - MONTHLY[i][1]), 'стены') * lo
        prev_lo = max(MONTHLY[i - 1][0], 100)
        base = net(RRC['стены'][0] * (1 - MONTHLY[i - 1][1]), 'стены') * prev_lo
        print(f'  порог {lo:>5} м²: на самом пороге {after - before:>7,.0f} $/мес, '
              f'против прошлой ступени +{after - base:,.0f} $/мес')




def progressive(v, k='стены'):
    """Прогрессивная шкала: скидка применяется к объёму сверх порога.
    Возвращает (сумма к оплате, эффективная скидка)."""
    R = RRC[k][0]
    total = 0.0
    for i, (lo, disc, _) in enumerate(MONTHLY):
        hi = MONTHLY[i + 1][0] if i + 1 < len(MONTHLY) else float('inf')
        take = max(0.0, min(v, hi) - lo)
        total += take * R * (1 - disc)
    return total, 1 - total / (v * R) if v else 0.0


def dead_zones():
    print('\nСТУПЕНЧАТАЯ ШКАЛА: МЁРТВЫЕ ЗОНЫ')
    print('  объём, при котором мы зарабатываем меньше, чем на метр до порога')
    for i in range(1, len(MONTHLY)):
        lo = MONTHLY[i][0]
        prev = net(RRC['стены'][0] * (1 - MONTHLY[i - 1][1]), 'стены')
        cur = net(RRC['стены'][0] * (1 - MONTHLY[i][1]), 'стены')
        need = (lo - 1) * prev / cur
        print(f'  порог {lo:>5} м²: до порога {(lo - 1) * prev:>7,.0f} $/мес, '
              f'сразу после {lo * cur:>7,.0f} — догоняем только к {need:>5.0f} м²')


def progressive_table():
    print('\nПРОГРЕССИВНАЯ ШКАЛА — та же вилка, без мёртвых зон')
    print(f'  {"м²/мес":>8}{"ступенчато":>13}{"прогрессивно":>15}{"эфф. скидка":>13}'
          f'{"наш $/мес ступ":>16}{"прогр":>9}')
    for v in (50, 100, 200, 250, 300, 500, 700, 1000, 1500):
        d = tier(v)
        step_pay = v * RRC['стены'][0] * (1 - d)
        prog_pay, eff = progressive(v)
        cost = MAT['стены'] * v
        step_net = (step_pay - cost) / (1 + VAT) * (1 - PROFIT_TAX)
        prog_net = (prog_pay - cost) / (1 + VAT) * (1 - PROFIT_TAX)
        print(f'  {v:>8}{step_pay:>13,.0f}{prog_pay:>15,.0f}{eff:>13.1%}'
              f'{step_net:>16,.0f}{prog_net:>9,.0f}')




# ── стык объектной шкалы и дилерской ──────────────────────────────────────
# Дилерская скидка считается от РРЦ КОНКРЕТНОГО объекта, а не от базовой
# цены. Иначе на объектах от 120 м², где РРЦ уже упала до дна, дилеру
# не остаётся ничего.
DEALER_FROM_OBJECT_PRICE = True


def dealer_buy(area, k, disc):
    """Цена закупки для дилера под конкретный объект."""
    base = rrc(area, k) if DEALER_FROM_OBJECT_PRICE else RRC[k][0]
    return base * (1 - disc)


def clash():
    print('\nСТЫК ДВУХ ФОРМУЛ: объектная шкала против дилерской')
    for disc in (0.34, 0.40):
        print(f'\n  скидка {disc:.0%}')
        print(f'  {"объект":>8}{"РРЦ":>8}   от базовой РРЦ: {"закуп":>7}{"дилер":>7}{"нам":>7}'
              f'   |  от РРЦ объекта: {"закуп":>7}{"дилер":>7}{"нам":>7}')
        for a in (20, 50, 80, 100, 120, 200):
            k = 'стены'
            r = rrc(a, k)
            zA, zB = RRC[k][0] * (1 - disc), r * (1 - disc)
            P = r * (1 - HAGGLE)
            dA = (P - zA) / (1 + VAT) * (1 - PROFIT_TAX) - KICKBACK * P
            dB = (P - zB) / (1 + VAT) * (1 - PROFIT_TAX) - KICKBACK * P
            print(f'  {a:>8}{r:>8.2f}{"":>18}{zA:>7.2f}{dA:>7.2f}{net(zA, k):>7.2f}'
                  f'{"":>21}{zB:>7.2f}{dB:>7.2f}{net(zB, k):>7.2f}')


